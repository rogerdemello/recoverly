"""Recoverly deterministic scoring library (standard library only).

Uploaded to the CreateOS Sandbox next to the generated script. The generated script writes the
question-specific filter logic; everything below (states, scoring, ranking, reasons, metrics, result
assembly) is fixed code and is NEVER regenerated by the model.

Rules implemented here are specified in docs/technical-spec.md section 3. Money is always integer
minor units. Scores are only comparable within one currency.
"""
from __future__ import annotations

import json
import math
from datetime import datetime, timezone

SCHEMA_VERSION = "1"

# Weights are frozen: amount 0.45, recovery 0.25, urgency 0.20, customer value 0.10.
RECOVERY = {
    "expired_card": 0.90,
    "authentication_required": 0.80,
    "insufficient_funds": 0.60,
    "processing_error": 0.50,
    "generic_decline": 0.35,
    "do_not_honor": 0.35,
    "call_issuer": 0.35,
    "card_velocity_exceeded": 0.35,
    "lost_card": 0.10,
    "stolen_card": 0.10,
    "fraudulent": 0.10,
    "merchant_blacklist": 0.10,
    "pickup_card": 0.10,
    "restricted_card": 0.10,
}
DEFAULT_RECOVERY = 0.30
NON_DISCLOSABLE = {
    "lost_card",
    "stolen_card",
    "fraudulent",
    "merchant_blacklist",
    "pickup_card",
    "restricted_card",
}
GENERIC_CODES = {"generic_decline", "do_not_honor", "call_issuer", "card_velocity_exceeded"}

MEANING = {
    "expired_card": "Card has expired; customer must supply a new card",
    "authentication_required": "Payment needs customer authentication",
    "insufficient_funds": "Insufficient funds; a retry may succeed",
    "processing_error": "Processing error, possibly transient",
}

RESOLVED_STATES = {"recovered", "not_recovered"}
TIERS = {"low": 0, "medium": 1, "high": 2, "urgent": 3}
REQUIRED = ("invoice_id", "customer_id", "amount_due", "currency", "failed_at", "failure_code")

ZERO_DECIMAL = {
    "bif", "clp", "djf", "gnf", "jpy", "kmf", "krw", "mga", "pyg", "rwf", "ugx", "vnd", "vuv", "xaf", "xof", "xpf",
}
SYMBOLS = {"usd": "$", "eur": "€", "gbp": "£", "jpy": "¥"}


# ---------------------------------------------------------------- helpers

def round1(x):
    """Half-up rounding to 1 decimal (never Python's banker's round)."""
    return math.floor(x * 10 + 0.5) / 10


def round3(x):
    return math.floor(x * 1000 + 0.5) / 1000


def parse_ts(value):
    if not value or not isinstance(value, str):
        return None
    try:
        parsed = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def iso(ts):
    return ts.strftime("%Y-%m-%dT%H:%M:%SZ")


def _int(value):
    try:
        return int(value)
    except (TypeError, ValueError):
        return 0


def _blank(value):
    return value is None or value == ""


def format_money(minor, currency):
    cur = (currency or "").lower()
    exp = 0 if cur in ZERO_DECIMAL else 2
    major = minor / (10 ** exp)
    text = f"{major:,.{exp}f}"
    symbol = SYMBOLS.get(cur)
    return f"{symbol}{text}" if symbol else f"{cur.upper()} {text}"


# ---------------------------------------------------------------- loading and context

def load(path="data.json"):
    """The only way a script may read data. Returns (as_of, records)."""
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    as_of = parse_ts(payload["as_of"])
    if as_of is None:
        raise ValueError("data.json has an invalid as_of")
    return as_of, payload["records"]


def _classify(record, as_of):
    """Section 3.1 state machine. Returns (state, retry_status)."""
    status = (record.get("invoice_status") or "").lower()
    npa = record.get("next_payment_attempt")
    npa_ts = parse_ts(npa) if not _blank(npa) and npa != "unknown" else None
    if npa == "unknown":
        retry = "unknown"
    elif npa_ts is not None and npa_ts > as_of:
        retry = "scheduled"
    else:
        retry = "none_scheduled"

    if status == "paid":
        return "recovered", retry
    if status in ("void", "uncollectible"):
        return "not_recovered", retry
    if any(_blank(record.get(f)) for f in REQUIRED) or parse_ts(record.get("failed_at")) is None:
        return "unknown", retry
    if npa == "unknown":
        return "failed", retry
    if retry == "scheduled":
        return "in_recovery", retry
    return "action_needed", retry


def build_context(records, as_of):
    """max_amount per currency over ALL queued records of the FULL dataset (so scores do not move between questions)."""
    max_amount = {}
    queued_counts = {}
    for record in records:
        state, _ = _classify(record, as_of)
        if state in RESOLVED_STATES:
            continue
        cur = (record.get("currency") or "").lower()
        max_amount[cur] = max(max_amount.get(cur, 0), _int(record.get("amount_due")))
        queued_counts[cur] = queued_counts.get(cur, 0) + 1
    return {"as_of": as_of, "max_amount": max_amount, "queued_counts": queued_counts}


# ---------------------------------------------------------------- per-record enrichment

def _action(state, confidence, code, attempts, priority, amount):
    """Section 3.5, first match wins."""
    if state in RESOLVED_STATES:
        return "do_not_pursue"
    if state == "unknown" or confidence == "low":
        return "review_manually"
    if code in NON_DISCLOSABLE:
        return "review_manually"
    if code in ("expired_card", "authentication_required"):
        return "update_payment_method"
    if state == "in_recovery":
        return "wait_for_retry"
    if attempts >= 3 or priority == "urgent":
        return "contact_customer"
    if amount >= 10000 and code == "generic_decline":
        return "review_manually"
    return "contact_customer"


def _meaning(code):
    if code in MEANING:
        return MEANING[code]
    if code in GENERIC_CODES:
        return "Card declined, reason unknown"
    if code in NON_DISCLOSABLE:
        return "Card declined, reason not disclosed"
    return "Unrecognized failure code"


def enrich(record, ctx):
    """Applies sections 3.1 to 3.6 to one record. Resolved records get priority=None, score=None.

    `days_since_failure` and `components` are returned UNROUNDED (build_result rounds for output);
    `score` is rounded to 1 decimal immediately because tiers are defined on the rounded score.
    """
    as_of = ctx["as_of"]
    state, retry = _classify(record, as_of)
    cur = (record.get("currency") or "").lower()
    code = (record.get("failure_code") or "").lower()
    amount = _int(record.get("amount_due"))
    attempts = _int(record.get("attempt_count"))
    failed_at = parse_ts(record.get("failed_at"))
    created = parse_ts(record.get("customer_created_at"))
    npa = record.get("next_payment_attempt")
    resolved = state in RESOLVED_STATES

    days = max(0.0, (as_of - failed_at).total_seconds() / 86400.0) if failed_at else 0.0
    future = bool(failed_at and failed_at > as_of)

    missing = []
    if _blank(record.get("failure_message")):
        missing.append("failure_message")
    if created is None:
        missing.append("customer_created_at")
    if _blank(record.get("subscription_id")):
        missing.append("subscription_id")
    if _blank(record.get("hosted_invoice_url")):
        missing.append("hosted_invoice_url")
    if npa == "unknown":
        missing.append("next_payment_attempt")
    if code not in RECOVERY:
        missing.append("failure_code_unrecognized")

    if state == "unknown" or len(missing) >= 2:
        confidence = "low"
    elif len(missing) == 1:
        confidence = "medium"
    else:
        confidence = "high"

    next_at = None
    if retry == "scheduled":
        next_at = iso(parse_ts(npa))

    components = None
    score = None
    priority = None
    reason = ""
    recovery = RECOVERY.get(code, DEFAULT_RECOVERY)
    urgency = None
    if resolved:
        reason = "Invoice is paid." if state == "recovered" else f"Invoice is {(record.get('invoice_status') or '').lower()}."
    else:
        max_amt = ctx["max_amount"].get(cur, 0)
        amount_norm = (amount / max_amt) if max_amt > 0 else 0.0
        urgency = min(
            1.0,
            min(days / 14.0, 1.0) * 0.5
            + (0.30 if npa == "" and retry != "scheduled" else 0.0)
            + (0.20 if attempts >= 3 else 0.0),
        )
        tenure = (as_of - created).total_seconds() / 86400.0 if created else 0.0
        value = min(max(tenure, 0.0) / 365.0, 1.0) if created else 0.0
        components = {"amount_norm": amount_norm, "recovery": recovery, "urgency": urgency, "value": value}
        score = round1(100 * (0.45 * amount_norm + 0.25 * recovery + 0.20 * urgency + 0.10 * value))
        priority = "urgent" if score >= 60 else "high" if score >= 45 else "medium" if score >= 30 else "low"

        drivers = [
            ("amount at risk", 45 * amount_norm),
            ("likelihood of recovery", 25 * recovery),
            ("urgency", 20 * urgency),
            ("customer tenure", 10 * value),
        ]
        top = max(drivers, key=lambda d: d[1])[0]
        if retry == "scheduled":
            retry_text = f"A retry is scheduled for {next_at}."
        elif retry == "unknown":
            retry_text = "Retry information is unavailable."
        else:
            retry_text = "No retry is scheduled."
        reason = f"{_meaning(code)}. {retry_text} Largest score driver: {top}."

    action = _action(state, confidence, code, attempts, priority, amount)

    def fact(field, value):
        return {"field": field, "value": None if _blank(value) else value, "source": "stripe_fact"}

    def inferred(field, value):
        return {"field": field, "value": value, "source": "agent_inference"}

    evidence = [
        fact("amount_due", amount),
        fact("currency", cur),
        fact("failure_code", code),
        fact("failure_message", record.get("failure_message")),
        fact("attempt_count", attempts),
        fact("next_payment_attempt", npa),
        fact("invoice_status", record.get("invoice_status")),
        fact("failed_at", record.get("failed_at")),
        fact("customer_created_at", record.get("customer_created_at")),
        inferred("days_since_failure", round3(days)),
        inferred("retry_status", retry),
    ]
    if not resolved:
        evidence += [
            inferred("recovery_signal", recovery),
            inferred("urgency", round3(urgency)),
            inferred("priority", priority),
        ]
    evidence += [inferred("recommended_action", action), inferred("confidence", confidence)]

    return {
        "invoice_id": record.get("invoice_id") or "",
        "customer_id": record.get("customer_id") or "",
        "customer_email_masked": record.get("customer_email_masked") or "",
        "subscription_id": None if _blank(record.get("subscription_id")) else record.get("subscription_id"),
        "currency": cur,
        "amount_minor": amount,
        "state": state,
        "priority": priority,
        "score": score,
        "components": components,
        "recommended_action": action,
        "reason": reason,
        "confidence": confidence,
        "missing_inputs": missing,
        "failure_code": code,
        "attempt_count": attempts,
        "days_since_failure": days,
        "retry": {"status": retry, "next_attempt_at": next_at},
        "hosted_invoice_url_present": not _blank(record.get("hosted_invoice_url")),
        "evidence": evidence,
        "_future": future,
        "_single": (not resolved) and ctx["queued_counts"].get(cur, 0) == 1,
    }


# ---------------------------------------------------------------- ranking, metrics, result

def rank_queues(items, top_n):
    """Splits queued from resolved items; one queue per currency; ranks after sorting."""
    groups = {}
    for item in items:
        if item["state"] in RESOLVED_STATES:
            continue
        groups.setdefault(item["currency"], []).append(item)
    queues = []
    truncated = {}
    for cur, members in groups.items():
        members = sorted(members, key=lambda i: (-i["score"], -i["amount_minor"], i["invoice_id"]))
        ranked = []
        for position, member in enumerate(members, start=1):
            ranked.append({**member, "rank": position})
        truncated[cur] = len(ranked) > top_n
        queues.append({"currency": cur, "items": ranked[:top_n]})
    return queues, truncated


def metrics(items):
    """The metrics object of section 4.1 (computed over all in-scope items, before top_n truncation)."""
    by_currency = {}
    codes = {}
    states = {}
    for item in items:
        cur = item["currency"]
        bucket = by_currency.setdefault(
            cur,
            {
                "currency": cur,
                "failed_count": 0,
                "_customers": set(),
                "amount_at_risk_minor": 0,
                "in_recovery_minor": 0,
                "action_needed_minor": 0,
                "failed_minor": 0,
            },
        )
        state = item["state"]
        amount = item["amount_minor"]
        slot = states.setdefault((cur, state), {"currency": cur, "state": state, "count": 0, "amount_minor": 0})
        slot["count"] += 1
        slot["amount_minor"] += amount
        if state in RESOLVED_STATES:
            continue
        bucket["failed_count"] += 1
        bucket["_customers"].add(item["customer_id"])
        bucket["amount_at_risk_minor"] += amount
        if state == "in_recovery":
            bucket["in_recovery_minor"] += amount
        elif state == "action_needed":
            bucket["action_needed_minor"] += amount
        else:
            bucket["failed_minor"] += amount
        code_slot = codes.setdefault(
            (cur, item["failure_code"]),
            {"currency": cur, "failure_code": item["failure_code"], "count": 0, "amount_minor": 0},
        )
        code_slot["count"] += 1
        code_slot["amount_minor"] += amount

    currency_rows = []
    for bucket in by_currency.values():
        row = {k: v for k, v in bucket.items() if k != "_customers"}
        row["affected_customers"] = len(bucket["_customers"])
        currency_rows.append(
            {
                "currency": row["currency"],
                "failed_count": row["failed_count"],
                "affected_customers": row["affected_customers"],
                "amount_at_risk_minor": row["amount_at_risk_minor"],
                "in_recovery_minor": row["in_recovery_minor"],
                "action_needed_minor": row["action_needed_minor"],
                "failed_minor": row["failed_minor"],
            }
        )
    return {
        "by_currency": currency_rows,
        "by_failure_code": sorted(codes.values(), key=lambda r: (-r["amount_minor"], r["failure_code"])),
        "by_state": sorted(
            states.values(),
            key=lambda r: (list(by_currency).index(r["currency"]), -r["amount_minor"], r["state"]),
        ),
    }


def _public(item):
    """Output-shaped item: rounded numbers, internal keys removed."""
    out = {k: v for k, v in item.items() if not k.startswith("_")}
    out["days_since_failure"] = round3(item["days_since_failure"])
    out["components"] = {k: round3(v) for k, v in item["components"].items()}
    return out


def _summary(items, metric_rows):
    queued = [i for i in items if i["state"] not in RESOLVED_STATES]
    if not items:
        return "No records matched the plan filters."
    if not queued:
        return f"No unresolved failed payments in scope ({len(items)} resolved invoices excluded)."
    parts = []
    for row in metric_rows["by_currency"]:
        if row["failed_count"] == 0:
            continue
        parts.append(
            f"{format_money(row['amount_at_risk_minor'], row['currency'])} at risk "
            f"({row['failed_count']} invoice{'' if row['failed_count'] == 1 else 's'}, "
            f"{row['affected_customers']} customer{'' if row['affected_customers'] == 1 else 's'})"
        )
    resolved = len(items) - len(queued)
    tail = f" {resolved} resolved invoice(s) excluded from the queues." if resolved else ""
    return f"{len(queued)} failed payments need attention: " + "; ".join(parts) + "." + tail


def build_result(plan, as_of, records_total, items, queues, truncated, extra_warnings):
    """Assembles the AnalysisResult of section 4.1 and rounds for output."""
    queued = [i for i in items if i["state"] not in RESOLVED_STATES]
    resolved = [i for i in items if i["state"] in RESOLVED_STATES]
    metric_rows = metrics(items)

    warnings = []
    currencies = []
    for item in items:
        if item["currency"] not in currencies:
            currencies.append(item["currency"])
    single = []
    for item in queued:
        if item["_single"] and item["currency"] not in single:
            single.append(item["currency"])
    for cur in single:
        warnings.append(f"single_item_currency:{cur}")
    missing_count = sum(1 for i in queued if i["missing_inputs"])
    if missing_count:
        warnings.append(f"missing_inputs:{missing_count}_records")
    unrecognized = []
    for item in queued:
        if "failure_code_unrecognized" in item["missing_inputs"] and item["failure_code"] not in unrecognized:
            unrecognized.append(item["failure_code"])
    for code in unrecognized:
        warnings.append(f"unrecognized_failure_code:{code}")
    for item in queued:
        if item["_future"]:
            warnings.append(f"failed_at_in_future:{item['invoice_id']}")
    if not items:
        warnings.append("empty_scope")
    if any(truncated.values()):
        warnings.append(f"truncated:top_n={plan.get('top_n')}")
    warnings.extend(extra_warnings or [])

    return {
        "schema_version": SCHEMA_VERSION,
        "as_of": iso(as_of),
        "plan": plan,
        "summary": _summary(items, metric_rows),
        "metrics": {"records_total": records_total, "records_in_scope": len(items), **metric_rows},
        "queues": [{"currency": q["currency"], "items": [_public(i) for i in q["items"]]} for q in queues],
        "resolved": [
            {
                "invoice_id": i["invoice_id"],
                "customer_id": i["customer_id"],
                "currency": i["currency"],
                "amount_minor": i["amount_minor"],
                "state": i["state"],
                "recommended_action": "do_not_pursue",
                "reason": i["reason"],
            }
            for i in resolved
        ],
        "warnings": warnings,
        "data_quality": {
            "records_with_missing_inputs": missing_count,
            "unrecognized_failure_codes": unrecognized,
            "currencies": currencies,
            "single_item_currencies": single,
        },
    }
